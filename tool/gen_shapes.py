import json, math, pathlib

def circ(cx, cy, r): return f'M{cx-r} {cy} a{r} {r} 0 1 0 {2*r} 0 a{r} {r} 0 1 0 {-2*r} 0Z'
def ell(cx, cy, rx, ry): return f'M{cx-rx} {cy} a{rx} {ry} 0 1 0 {2*rx} 0 a{rx} {ry} 0 1 0 {-2*rx} 0Z'

def rot_ell(cx, cy, rx, ry, deg, n=28):
    a = math.radians(deg); pts = []
    for i in range(n):
        t = 2 * math.pi * i / n
        x, y = rx * math.cos(t), ry * math.sin(t)
        pts.append((cx + x * math.cos(a) - y * math.sin(a), cy + x * math.sin(a) + y * math.cos(a)))
    return 'M' + ' L'.join(f'{x:.1f} {y:.1f}' for x, y in pts) + 'Z'

def spikes(cx, cy, r1, r2, n=19):
    pts = []
    for i in range(n):
        ang = math.pi + i * math.pi / (n - 1)
        r = r1 if i % 2 == 0 else r2
        pts.append((cx + r * math.cos(ang), cy + r * math.sin(ang)))
    return 'M' + ' L'.join(f'{x:.1f} {y:.1f}' for x, y in pts) + 'Z'

def rrect(x, y, w, h, r):
    return (f'M{x+r} {y} L{x+w-r} {y} Q{x+w} {y} {x+w} {y+r} L{x+w} {y+h-r} Q{x+w} {y+h} {x+w-r} {y+h} '
            f'L{x+r} {y+h} Q{x} {y+h} {x} {y+h-r} L{x} {y+r} Q{x} {y} {x+r} {y}Z')
def star(cx, cy, R, r, n=5, rot=-90):
    pts = []
    for i in range(n * 2):
        a = math.radians(rot + i * 180 / n); rr = R if i % 2 == 0 else r
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return 'M' + ' L'.join(f'{x:.1f} {y:.1f}' for x, y in pts) + 'Z'
def star4(cx, cy, r):
    k = r * .28
    return f'M{cx} {cy-r} L{cx+k:.1f} {cy-k:.1f} L{cx+r} {cy} L{cx+k:.1f} {cy+k:.1f} L{cx} {cy+r} L{cx-k:.1f} {cy+k:.1f} L{cx-r} {cy} L{cx-k:.1f} {cy-k:.1f}Z'
def drop(cx, cy): return f'M{cx} {cy-5} Q{cx+4.2} {cy+1} {cx} {cy+4} Q{cx-4.2} {cy+1} {cx} {cy-5}Z'
def ray(a, r0=28, r1=46, spread=9):
    p = lambda ang, r: (50 + r * math.cos(math.radians(ang)), 50 + r * math.sin(math.radians(ang)))
    (x1, y1), (x2, y2), (x3, y3) = p(a - spread, r0), p(a, r1), p(a + spread, r0)
    return f'M{x1:.1f} {y1:.1f} L{x2:.1f} {y2:.1f} L{x3:.1f} {y3:.1f}Z'

